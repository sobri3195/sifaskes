const estimateCoordinate = (name) => {
  const hint = coordinateHints.find((item) => name.includes(item.keyword));
  if (hint) {
    return { latitude: hint.lat, longitude: hint.lng, isCoordinateEstimated: true };
  }
  return { latitude: -2.5, longitude: 118, isCoordinateEstimated: true };
};

const toFacility = ([name, type, jajaran], index) => ({
  id: `facility-${index + 1}`,
  name,
  type: facilityTypeOptions.includes(type) ? type : 'FKTP',
  jajaran,
  address: '',
  ...estimateCoordinate(name),
  accreditation: '',
  bedCount: 0,
  sdm: { ...emptySdm },
  profileNote: '',
  createdAt: new Date().toISOString(),
  updatedAt: new Date().toISOString(),
});

export const seedFacilities = rawFacilities.map(toFacility);
